 private void tampilData() {
    DefaultTableModel model =
            (DefaultTableModel) tblBarang.getModel();

    model.setRowCount(0);

    List<Barang> daftar = barangDAO.tampilkan();

    for (Barang b : daftar) {
        model.addRow(new Object[]{
            b.getKodeBarang(),
            b.getNamaBarang(),
            b.getKategori(),
            b.getStok()
        });
    }
}
