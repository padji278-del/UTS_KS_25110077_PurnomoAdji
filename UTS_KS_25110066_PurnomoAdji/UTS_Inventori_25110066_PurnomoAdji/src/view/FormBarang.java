    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        String kode = txtKode.getText().trim();
String nama = txtNama.getText().trim();
String kategori = cmbKategori.getSelectedItem().toString();
String stokText = txtStok.getText().trim();

// Validasi kode dan nama
if (kode.isEmpty() || nama.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Kode dan nama barang tidak boleh kosong!"
    );
    return;
}

// Validasi stok
int stok;

try {
    stok = Integer.parseInt(stokText);

    if (stok < 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Stok tidak boleh kurang dari 0!"
        );
        return;
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Stok harus berupa angka!"
    );
    return;
}

// Membuat objek Barang
Barang barang = new Barang(
    kode, nama, kategori, stok
);

// Menyimpan ke database
if (barangDAO.simpan(barang)) {

    javax.swing.JOptionPane.showMessageDialog(
        this, "Data barang berhasil disimpan!"
    );

    tampilData();

    txtKode.setText("");
    txtNama.setText("");
    txtStok.setText("");

} else {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Data gagal disimpan! Periksa kode barang."
    );
}
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void tblBarangMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBarangMouseClicked
        // TODO add your handling code here:
        int baris = tblBarang.getSelectedRow();

if (baris != -1) {
    txtKode.setText(
        tblBarang.getValueAt(baris, 0).toString()
    );

    txtNama.setText(
        tblBarang.getValueAt(baris, 1).toString()
    );

    cmbKategori.setSelectedItem(
        tblBarang.getValueAt(baris, 2).toString()
    );

    txtStok.setText(
        tblBarang.getValueAt(baris, 3).toString()
    );
}
    }//GEN-LAST:event_tblBarangMouseClicked

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        // TODO add your handling code here:
        String kode = txtKode.getText().trim();
String nama = txtNama.getText().trim();
String kategori = cmbKategori.getSelectedItem().toString();
String stokText = txtStok.getText().trim();

if (kode.isEmpty() || nama.isEmpty() || stokText.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Semua data harus diisi!"
    );
    return;
}

int stok;

try {
    stok = Integer.parseInt(stokText);

    if (stok < 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Stok tidak boleh negatif!"
        );
        return;
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Stok harus berupa angka!"
    );
    return;
}

Barang barang = new Barang(kode, nama, kategori, stok);

if (barangDAO.ubah(barang)) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Data berhasil diubah!"
    );

    tampilData();

    txtKode.setText("");
    txtNama.setText("");
    txtStok.setText("");

} else {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Data gagal diubah!"
    );
}
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        String kode = txtKode.getText().trim();

if (kode.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Pilih data barang dari tabel terlebih dahulu!"
    );
    return;
}

int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(
    this,
    "Yakin ingin menghapus barang dengan kode " + kode + "?",
    "Konfirmasi Hapus",
    javax.swing.JOptionPane.YES_NO_OPTION
);

if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {

    if (barangDAO.hapus(kode)) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Data berhasil dihapus!"
        );

        tampilData();
        txtKode.setText("");
        txtNama.setText("");
        txtStok.setText("");
        cmbKategori.setSelectedIndex(0);

    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Data gagal dihapus!"
        );
    }
}
    }//GEN-LAST:event_btnHapusActionPerformed

